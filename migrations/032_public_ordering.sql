-- 032_public_ordering.sql — public QR/kiosk ordering (SEC-7, FIT-11, FOH-13)
-- and the DB-9 state CHECKs. Expand-only: the previous revision never reads the
-- new tables, and every state value it writes is in the new CHECK sets.
-- Legacy signed QR/kiosk links stop working when this revision starts (by
-- design: they were 24 h links that sent unpaid orders to the kitchen).
-- No DML (no backfill, LD-6 not triggered), no role, no SECURITY DEFINER.
SET LOCAL lock_timeout = '5s';

-- 1. Per-restaurant settings (row absent = defaults) ---------------------------
CREATE TABLE public_ordering_settings (
  tenant_id uuid PRIMARY KEY REFERENCES restaurants(id),
  paused boolean NOT NULL DEFAULT false,
  table_policy text NOT NULL DEFAULT 'accept'
    CHECK (table_policy IN ('accept', 'pay_first')),
  counter_policy text NOT NULL DEFAULT 'accept'
    CHECK (counter_policy IN ('accept', 'pay_first')),
  hold_minutes integer NOT NULL DEFAULT 30
    CHECK (hold_minutes IN (10, 15, 20, 30, 45, 60, 90, 120)),
  -- minor units: MXN 100.00 .. 100,000.00, default 10,000.00
  max_order_total integer NOT NULL DEFAULT 1000000
    CHECK (max_order_total BETWEEN 10000 AND 10000000),
  version integer NOT NULL DEFAULT 1 CHECK (version >= 1),
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by uuid,
  FOREIGN KEY (tenant_id, updated_by) REFERENCES employees(tenant_id, id)
);

-- 2. Ordering links: opaque 128-bit bearer tokens, stored only as SHA-256 -------
-- token_hash = sha256('gm-public-link-v1:' || token), hex. No server secret is
-- involved, so rotating SIGNING_KEYS or JWT_SECRET never kills a printed QR.
CREATE TABLE public_links (
  tenant_id uuid NOT NULL REFERENCES restaurants(id),
  id uuid NOT NULL,
  token_hash text NOT NULL UNIQUE CHECK (token_hash ~ '^[0-9a-f]{64}$'),
  kind text NOT NULL CHECK (kind IN ('table', 'counter', 'kiosk')),
  channel text NOT NULL CHECK (channel IN ('qr', 'kiosk')),
  table_id uuid,
  label text NOT NULL DEFAULT '' CHECK (char_length(label) <= 60),
  created_by uuid NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  replaces_id uuid,
  revoked_at timestamptz,
  revoked_by uuid,
  revoke_reason text CHECK (revoke_reason IN ('revoked', 'rotated', 'abuse')),
  PRIMARY KEY (tenant_id, id),
  FOREIGN KEY (tenant_id, table_id) REFERENCES dining_tables(tenant_id, id),
  FOREIGN KEY (tenant_id, created_by) REFERENCES employees(tenant_id, id),
  FOREIGN KEY (tenant_id, revoked_by) REFERENCES employees(tenant_id, id),
  FOREIGN KEY (tenant_id, replaces_id) REFERENCES public_links(tenant_id, id),
  CONSTRAINT public_links_kind_shape CHECK (
    (kind = 'table'   AND channel = 'qr'    AND table_id IS NOT NULL) OR
    (kind = 'counter' AND channel = 'qr'    AND table_id IS NULL) OR
    (kind = 'kiosk'   AND channel = 'kiosk' AND table_id IS NULL)),
  CONSTRAINT public_links_revocation_complete CHECK (
    (revoked_at IS NULL) = (revoked_by IS NULL) AND
    (revoked_at IS NULL) = (revoke_reason IS NULL))
);
CREATE UNIQUE INDEX public_links_one_active_per_table
  ON public_links (tenant_id, table_id) WHERE revoked_at IS NULL AND kind = 'table';
CREATE INDEX public_links_active
  ON public_links (tenant_id, kind, created_at) WHERE revoked_at IS NULL;

-- Identity is immutable; the only transitions are a label edit while active and
-- one revocation. A revoked link never changes again.
CREATE FUNCTION public_link_transition() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF (NEW.tenant_id, NEW.id, NEW.token_hash, NEW.kind, NEW.channel, NEW.table_id,
      NEW.created_by, NEW.created_at, NEW.replaces_id)
     IS DISTINCT FROM
     (OLD.tenant_id, OLD.id, OLD.token_hash, OLD.kind, OLD.channel, OLD.table_id,
      OLD.created_by, OLD.created_at, OLD.replaces_id)
     OR (OLD.revoked_at IS NOT NULL AND
         (NEW.revoked_at, NEW.revoked_by, NEW.revoke_reason, NEW.label)
         IS DISTINCT FROM
         (OLD.revoked_at, OLD.revoked_by, OLD.revoke_reason, OLD.label))
  THEN
    RAISE EXCEPTION 'public_link_immutable';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER public_links_transition BEFORE UPDATE ON public_links
  FOR EACH ROW EXECUTE FUNCTION public_link_transition();

-- 3. Hold numbers (Q-14 / K-15) per restaurant business day --------------------
CREATE TABLE public_hold_numbers (
  tenant_id uuid NOT NULL REFERENCES restaurants(id),
  business_date date NOT NULL,
  value integer NOT NULL CHECK (value > 0),
  PRIMARY KEY (tenant_id, business_date)
);

-- 4. Held orders: no order, round, stock movement, job or ticket until accepted -
-- status_key_hash = sha256('gm-public-status-v1:' || statusKey); the 128-bit
-- status key is generated by the diner's browser and never returned. It is
-- unique per restaurant (every lookup is tenant-scoped), so a client that
-- reuses its key elsewhere cannot cause a cross-tenant unique violation.
CREATE TABLE public_order_holds (
  tenant_id uuid NOT NULL REFERENCES restaurants(id),
  id uuid NOT NULL,
  link_id uuid NOT NULL,
  operation_id uuid NOT NULL,                 -- the diner's idempotency key
  request_hash text NOT NULL CHECK (request_hash ~ '^[0-9a-f]{64}$'),
  status_key_hash text NOT NULL CHECK (status_key_hash ~ '^[0-9a-f]{64}$'),
  business_date date NOT NULL,
  number integer NOT NULL CHECK (number > 0),
  channel text NOT NULL CHECK (channel IN ('qr', 'kiosk')),
  mode text NOT NULL CHECK (mode IN ('dine_in', 'takeaway')),
  table_id uuid,
  policy text NOT NULL CHECK (policy IN ('accept', 'pay_first')),
  name text NOT NULL DEFAULT '' CHECK (char_length(name) <= 40),
  note text NOT NULL DEFAULT '' CHECK (char_length(note) <= 200),
  lines jsonb NOT NULL                        -- validated public LineInput[] (re-quoted at accept)
    CHECK (jsonb_typeof(lines) = 'array' AND jsonb_array_length(lines) BETWEEN 1 AND 40),
  priced jsonb NOT NULL                       -- display snapshot: id, quantity, name, optionNames, unitPrice, total
    CHECK (jsonb_typeof(priced) = 'array'),
  quoted_total integer NOT NULL CHECK (quoted_total >= 0),
  menu_revision bigint NOT NULL CHECK (menu_revision >= 0),
  order_operation_id uuid NOT NULL,           -- createOrder/addRound once() key used at accept
  state text NOT NULL DEFAULT 'pending'
    CHECK (state IN ('pending', 'accepted', 'rejected', 'cancelled')),
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  decided_at timestamptz,
  decided_by uuid,
  reject_reason text CHECK (reject_reason IN
    ('unavailable', 'duplicate', 'not_present', 'closed', 'abuse', 'other')),
  order_id uuid,
  order_round integer CHECK (order_round >= 1),
  excluded_line_ids uuid[] NOT NULL DEFAULT '{}',
  paid_at_accept boolean NOT NULL DEFAULT false,
  policy_override boolean NOT NULL DEFAULT false,
  PRIMARY KEY (tenant_id, id),
  UNIQUE (tenant_id, operation_id),
  UNIQUE (tenant_id, status_key_hash),
  UNIQUE (tenant_id, order_operation_id),
  UNIQUE (tenant_id, business_date, number),
  FOREIGN KEY (tenant_id, link_id) REFERENCES public_links(tenant_id, id),
  FOREIGN KEY (tenant_id, table_id) REFERENCES dining_tables(tenant_id, id),
  FOREIGN KEY (tenant_id, decided_by) REFERENCES employees(tenant_id, id),
  FOREIGN KEY (tenant_id, order_id) REFERENCES orders(tenant_id, id),
  CONSTRAINT public_order_holds_table_mode
    CHECK ((table_id IS NOT NULL) = (mode = 'dine_in')),
  CONSTRAINT public_order_holds_window
    CHECK (expires_at > created_at AND expires_at <= created_at + interval '2 hours'),
  CONSTRAINT public_order_holds_decision CHECK (
    (state = 'pending') = (decided_at IS NULL) AND
    (state = 'accepted') = (order_id IS NOT NULL AND order_round IS NOT NULL) AND
    (state = 'rejected') = (reject_reason IS NOT NULL) AND
    (state IN ('accepted', 'rejected')) = (decided_by IS NOT NULL) AND
    (state = 'accepted' OR
      (NOT paid_at_accept AND NOT policy_override AND cardinality(excluded_line_ids) = 0)))
);
CREATE INDEX public_order_holds_pending
  ON public_order_holds (tenant_id, created_at) WHERE state = 'pending';
CREATE INDEX public_order_holds_link_recent
  ON public_order_holds (tenant_id, link_id, created_at DESC);
CREATE INDEX public_order_holds_table_recent
  ON public_order_holds (tenant_id, table_id, created_at DESC) WHERE table_id IS NOT NULL;

-- Exactly one decision; the diner's request is immutable evidence.
CREATE FUNCTION public_order_hold_transition() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.state <> 'pending'
     OR NEW.state NOT IN ('accepted', 'rejected', 'cancelled')
     OR (NEW.tenant_id, NEW.id, NEW.link_id, NEW.operation_id, NEW.request_hash,
         NEW.status_key_hash, NEW.business_date, NEW.number, NEW.channel, NEW.mode,
         NEW.table_id, NEW.policy, NEW.name, NEW.note, NEW.lines, NEW.priced,
         NEW.quoted_total, NEW.menu_revision, NEW.order_operation_id,
         NEW.created_at, NEW.expires_at)
        IS DISTINCT FROM
        (OLD.tenant_id, OLD.id, OLD.link_id, OLD.operation_id, OLD.request_hash,
         OLD.status_key_hash, OLD.business_date, OLD.number, OLD.channel, OLD.mode,
         OLD.table_id, OLD.policy, OLD.name, OLD.note, OLD.lines, OLD.priced,
         OLD.quoted_total, OLD.menu_revision, OLD.order_operation_id,
         OLD.created_at, OLD.expires_at)
  THEN
    RAISE EXCEPTION 'public_order_hold_immutable';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER public_order_holds_transition BEFORE UPDATE ON public_order_holds
  FOR EACH ROW EXECUTE FUNCTION public_order_hold_transition();

-- 5. Row-level security ----------------------------------------------------------
DO $$ DECLARE t text; BEGIN
 FOREACH t IN ARRAY ARRAY['public_ordering_settings','public_links','public_hold_numbers','public_order_holds'] LOOP
  EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY',t);
  EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY',t);
  EXECUTE format('CREATE POLICY tenant_scope ON %I USING (tenant_id = nullif(current_setting(''app.tenant_id'',true),'''')::uuid) WITH CHECK (tenant_id = nullif(current_setting(''app.tenant_id'',true),'''')::uuid)',t);
 END LOOP;
END $$;
-- A diner has no tenant yet: it may read exactly the link whose hash it supplies
-- (same pattern as device_pairing_codes in 023 and restaurant_invitations in 014).
-- Only server/public-tokens.ts (resolveLink, resolveAnyLink) sets
-- app.public_link_hash, always to linkHash() of a well-formed token.
CREATE POLICY public_link_lookup ON public_links FOR SELECT
  USING (token_hash = nullif(current_setting('app.public_link_hash', true), ''));

-- 6. DB-9: state value sets. NOT VALID enforces every new INSERT/UPDATE at once
-- without scanning; 033 validates existing rows under SHARE UPDATE EXCLUSIVE.
-- orders.check_state is already constrained and validated by 024
-- (orders_check_state_valid). Adding a value later needs a new migration that
-- drops and re-adds the constraint (-- gm:contract-approved).
-- These ALTERs come last and in the order orders -> rounds -> jobs, the same
-- order in which every app transaction writes those tables (the job runner
-- claims and completes jobs in their own transactions), so the brief ACCESS
-- EXCLUSIVE locks cannot form a cycle with live traffic; lock_timeout and the
-- runner's 55P03 retry cover a busy table. Production: the deploy that first
-- carries 032 runs before 07:00 Mexico City once there is traffic (P-27).
ALTER TABLE orders
  ADD CONSTRAINT orders_state_valid CHECK (state IN
    ('active', 'ready', 'completed', 'cancelled', 'recovery_pending', 'recovery_reviewed')) NOT VALID,
  ADD CONSTRAINT orders_channel_valid CHECK (channel IN
    ('pos', 'qr', 'kiosk', 'offline')) NOT VALID,
  ADD CONSTRAINT orders_mode_valid CHECK (mode IN
    ('takeaway', 'dine_in', 'delivery')) NOT VALID;
ALTER TABLE rounds
  ADD CONSTRAINT rounds_state_valid CHECK (state IN
    ('active', 'ready', 'completed', 'offline_review')) NOT VALID;
ALTER TABLE jobs
  ADD CONSTRAINT jobs_state_valid CHECK (state IN
    ('queued', 'available', 'running', 'done', 'blocked', 'dead')) NOT VALID;
