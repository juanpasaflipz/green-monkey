#!/usr/bin/env bash
# Regenerates tests/fixtures/cfdi/test-csd.ts: SYNTHETIC, self-signed test certificates shaped like
# SAT's CSD (Certificado de Sello Digital) files, for the cfdi unit and DB tests. They are not SAT
# certificates and have no fiscal value; the RFC is SAT's public CFDI 4.0 test identity.
#
#   bash scripts/cfdi-make-test-csd.sh            (needs OpenSSL >= 3.4 for -not_before/-not_after)
#
# Shapes (spec §2.3, §4.6):
#   csd      .cer DER with the RFC in x500UniqueIdentifier (OID 2.5.4.45, "RFC / CURP"),
#            keyUsage digitalSignature+nonRepudiation; .key PKCS#8 DER encrypted with a password
#   fiel     same subject, keyUsage also keyEncipherment+dataEncipherment (an e.firma, not a CSD)
#   expired  valid 2019-2020
#   other    another RFC (URE180429TM6)
#   otherKey a second private key (key pair mismatch)
set -euo pipefail
OPENSSL=${OPENSSL:-openssl}
out=tests/fixtures/cfdi/test-csd.ts
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
password='12345678a'
serial=0x3330303031303030303030353030303033343136 # ASCII "30001000000500003416"

key() { # name
  "$OPENSSL" genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:2048 -out "$work/$1.pem" 2>/dev/null
  "$OPENSSL" pkcs8 -topk8 -v2 aes-256-cbc -in "$work/$1.pem" -outform DER -out "$work/$1.key" \
    -passout "pass:$password"
}
cert() { # name keyname rfc usage notBefore notAfter
  "$OPENSSL" req -new -x509 -key "$work/$2.pem" -sha256 -set_serial "$serial" \
    -subj "/CN=ESCUELA KEMPER URGATE/O=ESCUELA KEMPER URGATE/x500UniqueIdentifier=$3 \/ XXXX000000XXXXXX00/OU=Prueba" \
    -addext "keyUsage=critical,$4" -addext "basicConstraints=critical,CA:FALSE" \
    -not_before "$5" -not_after "$6" -outform DER -out "$work/$1.cer"
}

key main
key second
cert csd main EKU9003173C9 "digitalSignature,nonRepudiation" 20240101000000Z 20341231235959Z
cert fiel main EKU9003173C9 "digitalSignature,nonRepudiation,keyEncipherment,dataEncipherment" 20240101000000Z 20341231235959Z
cert expired main EKU9003173C9 "digitalSignature,nonRepudiation" 20190101000000Z 20201231235959Z
cert other main URE180429TM6 "digitalSignature,nonRepudiation" 20240101000000Z 20341231235959Z

b64() { base64 < "$1" | tr -d '\n'; }
{
  echo "// GENERATED by scripts/cfdi-make-test-csd.sh. SYNTHETIC self-signed test certificates shaped like"
  echo "// SAT CSD files (DER .cer, encrypted PKCS#8 DER .key); no fiscal value. Allowlisted in .gitleaks.toml."
  echo "export const TEST_CSD_PASSWORD = \"$password\";"
  echo "export const TEST_CSD_RFC = \"EKU9003173C9\";"
  echo "export const TEST_CSD_SERIAL = \"30001000000500003416\";"
  echo "export const TEST_CSD = {"
  echo "  cer: \"$(b64 "$work/csd.cer")\","
  echo "  key: \"$(b64 "$work/main.key")\","
  echo "  fielCer: \"$(b64 "$work/fiel.cer")\","
  echo "  expiredCer: \"$(b64 "$work/expired.cer")\","
  echo "  otherRfcCer: \"$(b64 "$work/other.cer")\","
  echo "  otherKey: \"$(b64 "$work/second.key")\","
  echo "};"
} > "$out"
npx prettier --write "$out" >/dev/null
echo "wrote $out"
